BLUEPRINT_MODULES = ("auth", "sales", "customers", "purchases", "inventory", "reports_gst", "payroll", "admin")


def init_app(app):
    import importlib
    for name in BLUEPRINT_MODULES:
        app.register_blueprint(importlib.import_module(f"{__name__}.{name}").bp)

    def _resolve_alias(error, endpoint, values):
        if endpoint in ENDPOINT_ALIASES:
            return url_for(ENDPOINT_ALIASES[endpoint], **values)
        return None  # not an alias: let Flask raise the original BuildError

    app.url_build_error_handlers.append(_resolve_alias)
